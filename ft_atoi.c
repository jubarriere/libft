#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		sign;
	int		i;
	int		result;
	char	*nb;

	nb = (char *)nptr;
	sign = 1;
	i = 0;
	result = 0;
	while ((nb[i] >= 9 && nb[i] <= 13) || nb[i] == ' ')
		i++;
	if (nb[i] == '-' || nb[i] == '+')
	{
		if (nb[i] == '-')
			sign = -1;
		i++;
	}
	while (nb[i] >= '0' && nb[i] <= '9')
	{
		result = result * 10 + (nb[i] - '0');
		i++;
	}
	return (result * sign);
}
