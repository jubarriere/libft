#include "libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	t_list	*last_node;

	last_node = lst;
	if (lst == NULL)
		return (NULL);
	while (last_node->next != NULL)
		last_node = last_node->next;
	return (last_node);
}
